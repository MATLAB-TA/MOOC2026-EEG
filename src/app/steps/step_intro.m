names = mooc_ui_step_names();
steps = struct( ...
    'name', names(2:7), ...
    'caption', {'脳波を読み込んで見る', 'フィルタでノイズを除く', ...
        'まばたき・筋肉などの成分を除く', '左右の拳で、電極の脳波の変化を比べる', ...
        '脳の中のどこが変化したかを推定する', 'ファイル（.set）に保存し、機械学習に使う'});
end

function chanlocs = localDisplayChanlocs()
% The 64 electrodes of the dataset, placed with EEGLAB's standard 10-5
% positions; the 19 electrodes of the 10-20 system if EEGLAB is missing.
names = {'Fc5', 'Fc3', 'Fc1', 'Fcz', 'Fc2', 'Fc4', 'Fc6', 'C5', 'C3', 'C1', 'Cz', ...
    'C2', 'C4', 'C6', 'Cp5', 'Cp3', 'Cp1', 'Cpz', 'Cp2', 'Cp4', 'Cp6', 'Fp1', 'Fpz', ...
    'Fp2', 'Af7', 'Af3', 'Afz', 'Af4', 'Af8', 'F7', 'F5', 'F3', 'F1', 'Fz', 'F2', 'F4', ...
    'F6', 'F8', 'Ft7', 'Ft8', 'T7', 'T8', 'T9', 'T10', 'Tp7', 'Tp8', 'P7', 'P5', 'P3', ...
    'P1', 'Pz', 'P2', 'P4', 'P6', 'P8', 'Po7', 'Po3', 'Poz', 'Po4', 'Po8', 'O1', 'Oz', ...
    'O2', 'Iz'};
try
    EEG = eeg_emptyset();
    EEG.chanlocs = struct('labels', names);
    EEG.nbchan = numel(names);
    [~, EEG] = evalc('pop_chanedit(EEG, ''lookup'', mooc_default_config().paths.channelLocationFile)');
    chanlocs = EEG.chanlocs;
    return;
catch
    % EEGLAB not installed yet: the environment check below says so
end
names = {'Fp1', 'Fp2', 'F7', 'F3', 'Fz', 'F4', 'F8', 'T7', 'C3', 'Cz', ...
    'C4', 'T8', 'P7', 'P3', 'Pz', 'P4', 'P8', 'O1', 'O2'};
theta = [-18 18 -54 -39 0 39 54 -90 -90 0 90 90 -126 -141 180 141 126 -162 162];
radius = [0.51 0.51 0.51 0.33 0.26 0.33 0.51 0.51 0.26 0 0.26 0.51 0.51 0.33 0.26 0.33 0.51 0.51 0.51];
chanlocs = struct('labels', names, 'theta', num2cell(theta), 'radius', num2cell(radius));
end

