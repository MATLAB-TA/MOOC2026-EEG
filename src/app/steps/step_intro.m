function api = step_intro(tab, state, nav)
%STEP_INTRO ステップ0「はじめに」の画面
%
%   演習の流れを示し、必要なソフトとデータがそろっているかを確かめる。

% ---- Layout --------------------------------------------------------------
ui = mooc_ui_page_layout(tab, state, nav, ...
    ['・演習全体の流れを確認する' newline ...
     '・解析に必要なソフトとデータがそろっているか確認する' newline newline ...
     '「環境を確認」を押してください。'], ...
    'ControlRows', {32}, 'DescriptionHeight', 130, 'NextStep', 2);

checkButton = uibutton(ui.controls, 'Text', '環境を確認', 'FontWeight', 'bold', 'Tag', 'stage:intro', ...
    'ButtonPushedFcn', @(~, ~) checkEnvironment());
checkButton.Layout.Column = [1 2];

plotGrid = uigridlayout(ui.plotArea, [4 1]);
plotGrid.RowHeight = {'1x', 34, 240, 195};
plotGrid.RowSpacing = 8;

% (1) What the data is
dataPanel = uipanel(plotGrid, 'Title', 'データの内容', 'FontWeight', 'bold', 'FontSize', 13);
dataGrid = uigridlayout(dataPanel, [1 3], 'ColumnWidth', {'1x', 340, 340}, 'ColumnSpacing', 16);
uilabel(dataGrid, 'WordWrap', 'on', 'VerticalAlignment', 'top', 'FontSize', 14, ...
    'Text', localDataText());
electrodeAxes = uiaxes(dataGrid);
mooc_topoplot(electrodeAxes, [], localDisplayChanlocs(), 'ShowNames', false, 'ShowSides', true);
disableDefaultInteractivity(electrodeAxes);
cueGrid = uigridlayout(dataGrid, [2 1], 'RowHeight', {'1x', 30}, 'Padding', [0 0 0 0]);
cue = mooc_ui_cue_display(cueGrid);
demoButton = uibutton(cueGrid, 'Text', '▶ 参加者の画面を再生', 'Tag', 'option', ...
    'ButtonPushedFcn', @(~, ~) toggleDemo());

% (2) From the data to the analysis
uilabel(plotGrid, 'HorizontalAlignment', 'center', 'FontSize', 15, 'FontWeight', 'bold', ...
    'Text', '↓　このデータをインターネット（PhysioNet）から取得し、次の6つのステップで解析します　↓');

% (3) The six steps as a row of pictures
stepGrid = uigridlayout(plotGrid, [1 11], 'Padding', [0 0 0 0], 'ColumnSpacing', 2, ...
    'ColumnWidth', [repmat({'1x', 16}, 1, 5), {'1x'}]);
steps = localStepTexts();
for k = 1:numel(steps)
    panel = uipanel(stepGrid, 'Title', sprintf('STEP %d', k), 'FontWeight', 'bold', 'FontSize', 12);
    inner = uigridlayout(panel, [3 1], 'RowHeight', {20, '1x', 40}, 'Padding', [2 2 2 4], ...
        'RowSpacing', 2);
    uilabel(inner, 'Text', steps(k).name, 'FontWeight', 'bold', 'FontSize', 12, ...
        'HorizontalAlignment', 'center');
    mooc_plot_step_comic(uiaxes(inner), k);
    uilabel(inner, 'Text', steps(k).caption, 'WordWrap', 'on', 'FontSize', 12, ...
        'HorizontalAlignment', 'center');
    if k < numel(steps)
        uilabel(stepGrid, 'Text', '→', 'FontSize', 20, 'HorizontalAlignment', 'center');
    end
end

% (4) Result of the environment check
resultPanel = uipanel(plotGrid, 'Title', '環境の確認結果', 'FontWeight', 'bold');
resultArea = uitextarea(uigridlayout(resultPanel, [1 1]), 'Editable', 'off', 'FontSize', 13, ...
    'Value', {'「環境を確認」を押すと、ここに結果が表示されます。'});

demoTimer = [];
api = struct('refresh', @startDemo, 'setNextEnabled', ...
    @(flag) set(ui.nextButton, 'Enable', matlab.lang.OnOffSwitchState(flag)), ...
    'checkEnvironment', @checkEnvironment, 'stop', @stopDemo);
startDemo();          % the participant's screen plays from the start

% ---- Callbacks -----------------------------------------------------------
    function allFound = checkEnvironment()
        % Not part of the processing history: nothing is done to the data.
        checks = localChecks();
        found = [checks.found];
        allFound = all(found);
        resultArea.Value = localResultText(checks);
        state.introDone = allFound;
        nav.update();
        if ~allFound
            uialert(ancestor(tab, 'figure'), ...
                sprintf('%d個の項目が見つかりません。解決方法は「環境の確認結果」を見てください。', ...
                    nnz(~found)), '環境の確認');
        end
    end

    function toggleDemo()
        if isempty(demoTimer)
            startDemo();
        else
            stopDemo();
        end
    end

    function stopDemo()
        if ~isempty(demoTimer) && isvalid(demoTimer)
            stop(demoTimer);
            delete(demoTimer);
        end
        demoTimer = [];
        demoButton.Text = '▶ 参加者の画面を再生';
    end

    function startDemo()
        % Also called when the tab is opened again (it stops on other tabs).
        if ~isempty(demoTimer)
            return;
        end
        sequence = {'rest', 'left_fist', 'rest', 'right_fist'};
        position = 0;
        demoTimer = timer('ExecutionMode', 'fixedRate', 'Period', 2, ...
            'Tag', 'mooc_app_timer', 'TimerFcn', @(~, ~) nextCue());
        demoButton.Text = '■ 停止';
        nextCue();
        start(demoTimer);

        function nextCue()
            position = mod(position, numel(sequence)) + 1;
            cue.show(sequence{position}, NaN);
        end
    end
end

