paths = mooc_default_config().paths;
subjects = dir(fullfile(paths.rawDir, 'S*'));
subjects = subjects([subjects.isdir]);
checks = struct( ...
    'label', { ...
        'MATLAB', ...
        'Signal Processing Toolbox', ...
        'EEGLAB（脳波解析ツール）', ...
        'BioSig（EDFファイルの読込）', ...
        'ICLabel（成分を分類するプログラム）', ...
        'FieldTrip-lite（頭のモデルの計算）', ...
        'ROIconnect（脳の領域ごとの活動）', ...
        '脳波データ（PhysioNet の EDF ファイル）'}, ...
    'found', { ...
        true, ...
        ~isempty(ver('signal')), ...
        ~isempty(which('pop_runica')), ...
        ~isempty(which('sopen')), ...
        ~isempty(which('pop_iclabel')), ...
        ~isempty(which('ft_prepare_leadfield')), ...
        ~isempty(which('pop_roi_activity')), ...
        ~isempty(subjects)}, ...
    'detail', { ...
        version('-release'), ...
        '周波数の計算（ステップ2〜5）で使用', ...
        'ステップ1〜6で使用', ...
        'ステップ1で使用', ...
        'ステップ3で使用', ...
        'ステップ5で使用', ...
        'ステップ5で使用', ...
        sprintf('%d人分', numel(subjects))}, ...
    'fix', { ...
        '', ...
        '「ホーム」→「アドオン」で追加する', ...
        'setup.m のセクション1・2を実行する', ...
        'setup.m のセクション3を実行する', ...
        'setup.m のセクション2を実行する', ...
        'setup.m のセクション2を実行する', ...
        'setup.m のセクション2を実行する', ...
        'setup.m のセクション4を実行する'});
end

function lines = localResultText(checks)
lines = {};
for k = 1:numel(checks)
    if checks(k).found
        lines{end + 1} = sprintf('○ %s　（%s）', checks(k).label, checks(k).detail); %#ok<AGROW>
    else
        lines{end + 1} = sprintf('× %s　→ %s', checks(k).label, checks(k).fix); %#ok<AGROW>
    end
end
if all([checks.found])
    lines{end + 1} = 'すべてそろっています。';
end
end
