function api = step_source(tab, state, nav)
%STEP_SOURCE ステップ5「信号源推定」の画面
%
%   電極の脳波から脳の68の領域の活動を推定し、強さの変化を左拳と右拳で比べる。

cfg = state.cfg;
group = mooc_ui_step_names(5);      % heading in the processing history
sensorimotor = {'precentral', 'postcentral'};    % motor and sensory cortex

% ---- Layout --------------------------------------------------------------
guide = struct('title', ['STEP ' group], 'picture', 5, 'lines', {{ ...
    'このステップでは、ステップ4で切り出した脳波から、脳の中のどこが働いたかを推定します。', ...
    '・電極は頭の表面にあるので、脳の中のどこの活動かは、そのままでは分からない', ...
    '・標準の頭の形（MRI）から、脳の表面の約5000点の活動が各電極にどう届くかを計算する（リードフィールド）', ...
    '・その逆をたどる計算（eLORETA）で、電極の波形から各点の活動を推定し、68の領域にまとめる', ...
    '左拳・右拳で、どの領域のμ波・β波が弱くなるかを比べ、ステップ4の電極の結果と見比べます。'}});
ui = mooc_ui_page_layout(tab, state, nav, ...
    ['・信号源推定：電極の波形から、脳の68の領域の活動を推定する（eLORETA）' newline ...
     '・左拳と右拳で、どの領域の脳波が弱くなるか比べる'], ...
    'ControlRows', {28, 28, 34, 'fit'}, 'NextStep', 7, 'Guide', guide, ...
    'HistoryGroup', group);

bandPicker = mooc_ui_band_picker(ui.controls, cfg, @() recomputeIfShown());
computeButton = uibutton(ui.controls, 'Text', '脳の活動を推定して比べる', 'Tag', 'stage:regionErd', ...
    'FontWeight', 'bold', 'ButtonPushedFcn', @(~, ~) computeSources());
computeButton.Layout.Column = [1 2];
dataLabel = uilabel(ui.controls, 'WordWrap', 'on', 'FontColor', [0.4 0.4 0.4], 'Text', ...
    '使うデータ：ステップ4で切り出した脳波（エポック）');
dataLabel.Layout.Column = [1 2];

% The same view as step 4: the left / right sensorimotor areas over time,
% and the brain from above, replayed in time.
erdView = mooc_ui_erd_view(ui.plotArea, cfg, localGuideLines());
erdView.clear('「脳の活動を推定して比べる」を押すと表示されます');

brain = [];          % cortex of the standard head, loaded for the first map

api = struct('refresh', @refresh, 'setNextEnabled', ...
    @(flag) set(ui.nextButton, 'Enable', matlab.lang.OnOffSwitchState(flag)), ...
    'computeSources', @computeSources, 'showFrame', erdView.showFrame, ...
    'stop', erdView.stop, 'guide', ui.guide);

% ---- Callbacks -----------------------------------------------------------
    function computeSources()
        if ~state.isDone('epoch')
            uialert(ancestor(tab, 'figure'), ...
                '先に「4. 左右の拳で脳の変化を比較」でエポックに分けてください。', '確認');
            return;
        end
        band = bandPicker.band();
        source = cfg.source;
        % The head model and the region signals are a save point: changing
        % the band only redoes the power calculation.
        steps = [ ...
            mooc_ui_step('source', '標準の頭のモデルを設定する', 'pop_dipfit_settings', @setHeadModel, ...
                {'dipfit = fileparts(which(''pop_dipfit_settings''));', ...
                 ['EEG = pop_dipfit_settings(EEG, ''hdmfile'', fullfile(dipfit, ''standard_BEM'', ''standard_vol.mat''), ' ...
                  '''coordformat'', ''MNI'', ''mrifile'', fullfile(dipfit, ''standard_BEM'', ''standard_mri.mat''), ' ...
                  '''chanfile'', fullfile(dipfit, ''standard_BEM'', ''elec'', ''standard_1005.elc''), ' ...
                  sprintf('''coord_transform'', %s, ''chansel'', 1:EEG.nbchan);', mat2str(source.coordTransform))]}), ...
            mooc_ui_step('source', '脳の約5000点の活動が、各電極にどう届くかを計算する（リードフィールド）', ...
                'pop_leadfield', @computeLeadfield, ...
                {['EEG = pop_leadfield(EEG, ''sourcemodel'', fullfile(fileparts(which(''eeglab'')), ''functions'', ' ...
                  '''supportfiles'', ''head_modelColin27_5003_Standard-10-5-Cap339.mat''), ' ...
                  sprintf('''sourcemodel2mni'', %s, ''downsample'', 1);', mat2str(source.sourceModel2mni))]}), ...
            mooc_ui_step('source', '68の領域ごとの活動を求める（eLORETA）', 'mooc_roi_activity', ...
                @computeRegions, ...
                {sprintf(['%% pop_roi_activity(EEG, ''model'', ''eLoreta'', ''modelparams'', {%g}, ' ...
                    '''atlas'', ''Desikan-Kilianny'', ''nPCA'', 1) と同じ計算を、メモリを節約するため領域ごとに行う'], ...
                    source.eloretaRegularization), ...
                 sprintf('EEG = mooc_roi_activity(EEG, %g);   %% 結果：EEG.roi.source_roi_data（領域 × 時間 × 試行）', ...
                    source.eloretaRegularization)}), ...
            mooc_ui_step('regionErd', sprintf('領域ごとに %s の強さの変化を計算（時間周波数解析）', band.displayName), ...
                'mooc_compute_erd', @computeRegionErd, ...
                {'% 68領域の活動を「チャンネル」に見立てて、ステップ4と同じ pop_newtimef を行う', ...
                 'regionEEG = EEG;', ...
                 'regionEEG.data = double(EEG.roi.source_roi_data);', ...
                 'regionEEG.nbchan = EEG.roi.nROI;', ...
                 'regionEEG.chanlocs = struct(''labels'', {EEG.roi.atlas.Scouts.Label});', ...
                 'regionEEG.icaweights = [];', ...
                 'regionEEG.icasphere = [];', ...
                 'regionEEG.icawinv = [];', ...
                 'regionEEG.icachansind = [];', ...
                 sprintf('erd = mooc_compute_erd(regionEEG, labels, [%g %g], [-1 0], cfg);', band.rangeHz)})];
        if state.isDone('source')
            steps = steps(4);
        end
        if mooc_ui_run_steps(state, group, steps, tab)
            redraw();
        end
        nav.update();

        function detail = setHeadModel()
            state.sourceEEG = pop_dipfit_settings(state.epochEEG, 'hdmfile', source.hdmFile, ...
                'coordformat', 'MNI', 'mrifile', source.mriFile, ...
                'chanfile', cfg.paths.channelLocationFile, ...
                'coord_transform', source.coordTransform, 'chansel', 1:state.epochEEG.nbchan);
            detail = 'EEGLAB 標準の頭（MNI 座標）';
        end

        function detail = computeLeadfield()
            state.sourceEEG = pop_leadfield(state.sourceEEG, 'sourcemodel', source.sourceModelFile, ...
                'sourcemodel2mni', source.sourceModel2mni, 'downsample', 1);
            detail = sprintf('%d電極 × 脳の%d点 × 3方向', state.sourceEEG.nbchan, ...
                numel(state.sourceEEG.dipfit.sourcemodel.leadfield));
        end

        function detail = computeRegions()
            state.sourceEEG = mooc_roi_activity(state.sourceEEG, source.eloretaRegularization);
            detail = sprintf('%d領域 × %d点 × %d回分', size(state.sourceEEG.roi.source_roi_data));
        end

        function detail = computeRegionErd()
            [regionEEG, regionNames, pointCount] = localRegionDataset(state.sourceEEG);
            erd = mooc_compute_erd(regionEEG, state.trialLabels, band.rangeHz, ...
                cfg.epoch.baselineSec, cfg);
            erd.regionNames = regionNames;
            erd.pointCount = pointCount;
            state.regionErd = erd;
            detail = sprintf('%d領域 × %d時点（左拳 %d回・右拳 %d回の平均）', ...
                numel(regionNames), numel(erd.times), erd.trialCount);
        end
    end

    function recomputeIfShown()
        if state.isDone('regionErd')
            computeSources();
        end
    end

% ---- Drawing ---------------------------------------------------------------
    function redraw()
        % Showing new results replays them from the beginning.
        erd = state.regionErd;
        band = bandPicker.band();
        if isempty(brain)
            brain = localBrainSurface(cfg.source.sourceModelFile);
        end
        erdView.show(struct('erd', erd, 'courses', localPool(erd, sensorimotor), ...
            'courseLabels', {{'左', '右'}}, 'courseRows', {{'左', '右'}}, ...
            'courseTitles', {{['左脳の運動野・感覚野（黒枠）の ' band.displayName], ...
                ['右脳の運動野・感覚野（黒枠）の ' band.displayName]}}, ...
            'map', 'brain', 'brain', brain, ...
            'highlight', {[strcat(sensorimotor, ' L'), strcat(sensorimotor, ' R')]}));
        erdView.play();
    end

    function refresh()
        % Opening the tab replays the results (from where they were).
        if state.isDone('regionErd')
            erdView.play();
        end
    end
end

% ---- Local functions -----------------------------------------------------
function [regionEEG, regionNames, pointCount] = localRegionDataset(EEG)
% The epochs with the 68 region signals in place of the electrodes, so that
% the same pop_newtimef analysis as in step 4 can be done on them.
regionNames = {EEG.roi.atlas.Scouts.Label};
pointCount = cellfun(@numel, {EEG.roi.atlas.Scouts.Vertices});
regionEEG = EEG;
regionEEG.data = double(EEG.roi.source_roi_data);
regionEEG.nbchan = numel(regionNames);
regionEEG.chanlocs = struct('labels', regionNames);
regionEEG.icaweights = [];
regionEEG.icasphere = [];
regionEEG.icawinv = [];
regionEEG.icachansind = [];
regionEEG.icaact = [];
regionEEG.dipfit = [];
regionEEG.roi = [];
end

function brain = localBrainSurface(sourceModelFile)
% The cortex of the standard head (Colin27) and its regions, for the maps.
model = load(sourceModelFile, 'cortex', 'atlas');
brain = struct('vertices', model.cortex.vertices, 'faces', model.cortex.faces, ...
    'region', model.atlas.colorTable(:), 'regionNames', {model.atlas.label(:)'});
end

function pooled = localPool(erd, regionTypes)
% ERD of the left and right hemisphere's REGIONTYPES taken together: their
% power is averaged, weighted by the number of points of each region.
pooled = erd;
pooled.names = {'左', '右'};
sides = {' L', ' R'};
pooled.power = zeros(2, size(erd.power, 2), size(erd.power, 3));
for side = 1:2
    rows = ismember(erd.regionNames, strcat(regionTypes, sides{side}));
    weights = erd.pointCount(rows) / sum(erd.pointCount(rows));
    pooled.power(side, :, :) = sum(erd.power(rows, :, :) .* weights(:), 1);
end
baselineColumns = erd.times >= erd.baselineSec(1) & erd.times <= erd.baselineSec(2);
baseline = mean(pooled.power(:, baselineColumns, :), 2);
pooled.percent = (pooled.power - baseline) ./ baseline * 100;
end

